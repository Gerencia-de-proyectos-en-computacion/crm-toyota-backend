CREATE SEQUENCE IF NOT EXISTS quote_number_seq START WITH 43 INCREMENT BY 1;

CREATE TABLE workshop_settings (
    id BIGINT PRIMARY KEY,
    business_name VARCHAR(150) NOT NULL,
    slogan VARCHAR(200) NOT NULL,
    ruc VARCHAR(11) NOT NULL,
    address VARCHAR(250) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(120),
    currency_symbol VARCHAR(10) NOT NULL DEFAULT 'S/',
    quote_validity_days INT NOT NULL DEFAULT 7,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    station_label VARCHAR(50) NOT NULL,
    role VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type VARCHAR(10) NOT NULL,
    document_number VARCHAR(15) NOT NULL UNIQUE,
    full_name VARCHAR(160) NOT NULL,
    phone VARCHAR(25) NOT NULL,
    email VARCHAR(120),
    address VARCHAR(220),
    data_consent_accepted BOOLEAN NOT NULL,
    data_consent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consent_version VARCHAR(25) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_customers_doc_number ON customers(document_number);
CREATE INDEX idx_customers_full_name ON customers(full_name);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    license_plate VARCHAR(15) NOT NULL UNIQUE,
    special_plate BOOLEAN NOT NULL DEFAULT FALSE,
    vin VARCHAR(30),
    model VARCHAR(50) NOT NULL,
    manufacture_year INT NOT NULL,
    trim_version VARCHAR(60) NOT NULL,
    current_mileage_km INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_vehicles_plate ON vehicles(license_plate);
CREATE INDEX idx_vehicles_customer ON vehicles(customer_id);

CREATE TABLE parts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    oem_reference_code VARCHAR(40) NOT NULL,
    brand VARCHAR(30) NOT NULL,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(40) NOT NULL,
    compatible_summary VARCHAR(140) NOT NULL,
    sale_price_igv NUMERIC(12, 2) NOT NULL,
    current_stock INT NOT NULL,
    min_stock INT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_parts_sku ON parts(sku);
CREATE INDEX idx_parts_oem_ref ON parts(oem_reference_code);
CREATE INDEX idx_parts_category ON parts(category);

CREATE TABLE part_compatibilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id BIGINT NOT NULL REFERENCES parts(id) ON DELETE CASCADE,
    model VARCHAR(50) NOT NULL,
    year_from INT NOT NULL,
    year_to INT NOT NULL,
    trim_version VARCHAR(60) NOT NULL DEFAULT 'ALL'
);

CREATE INDEX idx_part_compat_lookup ON part_compatibilities(part_id, model, year_from, year_to);

CREATE TABLE labor_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    service_name VARCHAR(160) NOT NULL,
    estimated_hours NUMERIC(5, 2) NOT NULL,
    interval_km INT,
    price_igv NUMERIC(12, 2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE maintenance_kits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    model VARCHAR(50) NOT NULL,
    interval_km INT NOT NULL,
    labor_rate_id BIGINT NOT NULL REFERENCES labor_rates(id),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_kits_model_km ON maintenance_kits(model, interval_km);

CREATE TABLE maintenance_kit_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id BIGINT NOT NULL REFERENCES maintenance_kits(id) ON DELETE CASCADE,
    part_id BIGINT NOT NULL REFERENCES parts(id),
    quantity INT NOT NULL
);

CREATE TABLE quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_number VARCHAR(25) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    mileage_at_quote INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    rejection_reason VARCHAR(30),
    rejection_notes VARCHAR(300),
    gross_total_igv NUMERIC(12, 2) NOT NULL,
    discount_percent NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    taxable_subtotal NUMERIC(12, 2) NOT NULL,
    igv_amount NUMERIC(12, 2) NOT NULL,
    final_total_igv NUMERIC(12, 2) NOT NULL,
    valid_until DATE NOT NULL,
    notes VARCHAR(300),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_quotes_number ON quotes(quote_number);
CREATE INDEX idx_quotes_status ON quotes(status);
CREATE INDEX idx_quotes_customer ON quotes(customer_id);
CREATE INDEX idx_quotes_vehicle ON quotes(vehicle_id);

CREATE TABLE quote_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    item_type VARCHAR(15) NOT NULL,
    part_id BIGINT REFERENCES parts(id),
    labor_rate_id BIGINT REFERENCES labor_rates(id),
    item_code VARCHAR(40) NOT NULL,
    description VARCHAR(180) NOT NULL,
    quantity INT NOT NULL,
    unit_price_igv NUMERIC(12, 2) NOT NULL,
    line_total_igv NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_quote_items_quote ON quote_items(quote_id);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id BIGINT NOT NULL REFERENCES parts(id),
    movement_type VARCHAR(35) NOT NULL,
    quantity_delta INT NOT NULL,
    stock_after INT NOT NULL,
    supplier_name VARCHAR(120),
    reference_doc VARCHAR(60),
    unit_cost NUMERIC(12, 2),
    performed_by VARCHAR(60) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_inv_movements_part ON inventory_movements(part_id, created_at);

CREATE TABLE ml_model_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version VARCHAR(60) NOT NULL,
    horizon_label VARCHAR(60) NOT NULL,
    r2 NUMERIC(6, 4) NOT NULL,
    wape NUMERIC(6, 4) NOT NULL,
    rmse NUMERIC(8, 4) NOT NULL,
    mape_nonzero NUMERIC(6, 4) NOT NULL,
    adi NUMERIC(6, 2) NOT NULL,
    execution_source VARCHAR(30) NOT NULL,
    calculated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE demand_forecasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id BIGINT NOT NULL UNIQUE REFERENCES parts(id) ON DELETE CASCADE,
    run_id BIGINT NOT NULL REFERENCES ml_model_runs(id),
    predicted_demand NUMERIC(10, 2) NOT NULL,
    reorder_point INT NOT NULL,
    suggested_order_qty INT NOT NULL,
    adi NUMERIC(6, 2) NOT NULL,
    calculated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_demand_forecasts_part ON demand_forecasts(part_id);
